"""
unicorn_research_cache.py — LLM Research Point Cache

Stores Advocate/Skeptic debate points generated by LLM agents with TTL.
The 5-min cron execution path loads cached points and runs pure-Python
verification + scoring — zero LLM latency on the execution path.

Research is generated async (manual or separate cron) and cached to disk.
Cache validity: 15 minutes by default. Market conditions don't change
fast enough to justify re-running LLMs every 5 min.
"""

import json
import os
import time
from pathlib import Path

from unicorn_logger import log_cache, log_error, PHASE_CACHE

CACHE_DIR = Path(__file__).parent / "data" / "unicorn_cache"
CACHE_TTL = int(os.environ.get("UNICORN_CACHE_TTL", 900))  # 15 min

CACHE_DIR.mkdir(parents=True, exist_ok=True)


def cache_path(gate_type: str) -> Path:
    """Disk path for a gate's debate points cache."""
    return CACHE_DIR / f"debate_points_{gate_type.lower()}.json"


def save_debate_points(
    gate_type: str,
    advocate_pts: list,
    skeptic_pts: list,
    raw_snapshot_signature: str = "",
) -> bool:
    """Save LLM-generated debate points to disk cache.

    Args:
        gate_type: "NOT_UP" or "NOT_DOWN"
        advocate_pts: [{family, claim, evidence}] from Advocate LLM
        skeptic_pts: [{family, claim, evidence}] from Skeptic LLM
        raw_snapshot_signature: Optional hash/timestamp from raw data
            to detect stale cache vs changed market state.

    Returns True if saved successfully.
    """
    cache = {
        "gate_type": gate_type,
        "cached_at": time.time(),
        "cached_at_iso": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "ttl": CACHE_TTL,
        "raw_signature": raw_snapshot_signature,
        "advocate_pts": advocate_pts,
        "skeptic_pts": skeptic_pts,
    }
    try:
        cpath = cache_path(gate_type)
        tmppath = cpath.with_suffix(cpath.suffix + ".tmp")
        tmppath.write_text(json.dumps(cache, indent=2))
        os.replace(tmppath, cpath)  # atomic on Linux (same filesystem)
        log_cache(
            gate=gate_type,
            hit=True,
            age=0,
            saved_advocate=len(advocate_pts),
            saved_skeptic=len(skeptic_pts),
        )
        return True
    except Exception as e:
        log_error(PHASE_CACHE, "save_debate_points failed", gate=gate_type, exception=e)
        return False


def load_debate_points(
    gate_type: str,
    max_age_sec: int = None,
    raw_signature: str = "",
) -> tuple:
    """Load cached debate points if still valid.

    Args:
        gate_type: "NOT_UP" or "NOT_DOWN"
        max_age_sec: Override default TTL (default: CACHE_TTL from env).
        raw_signature: If provided and cache has a different signature,
            cache is considered stale even if within TTL. Pass empty
            string to skip signature check.

    Returns:
        (advocate_pts, skeptic_pts) if cache valid, else (None, None).
    """
    ttl = max_age_sec if max_age_sec is not None else CACHE_TTL
    cpath = cache_path(gate_type)

    if not cpath.exists():
        log_cache(gate=gate_type, hit=False, reason="no_cache_file")
        return None, None

    try:
        cache = json.loads(cpath.read_text())
    except (json.JSONDecodeError, OSError) as e:
        log_cache(gate=gate_type, hit=False, reason="corrupt_cache")
        return None, None

    age = time.time() - cache.get("cached_at", 0)
    if age > ttl:
        log_cache(gate=gate_type, hit=False, age=age, reason="expired", ttl=ttl)
        return None, None

    if raw_signature and cache.get("raw_signature") != raw_signature:
        log_cache(
            gate=gate_type,
            hit=False,
            age=age,
            reason="signature_mismatch",
            cached_sig=cache.get("raw_signature"),
            current_sig=raw_signature,
        )
        return None, None

    advocate_pts = cache.get("advocate_pts")
    skeptic_pts = cache.get("skeptic_pts")

    if not advocate_pts or not skeptic_pts:
        log_cache(gate=gate_type, hit=False, age=age, reason="empty_points")
        return None, None

    log_cache(
        gate=gate_type,
        hit=True,
        age=age,
        advocate_count=len(advocate_pts),
        skeptic_count=len(skeptic_pts),
    )
    return advocate_pts, skeptic_pts


def cache_age_sec(gate_type: str) -> float | None:
    """Return age of cached points in seconds, or None if no cache."""
    cpath = cache_path(gate_type)
    if not cpath.exists():
        return None
    try:
        cache = json.loads(cpath.read_text())
        return time.time() - cache.get("cached_at", 0)
    except Exception:
        return None


def invalidate_cache(gate_type: str = None):
    """Delete cached points. If gate_type is None, invalidate all."""
    if gate_type:
        cpath = cache_path(gate_type)
        if cpath.exists():
            cpath.unlink()
    else:
        for cpath in CACHE_DIR.glob("debate_points_*.json"):
            cpath.unlink()


def compute_signature(raw_data: dict) -> str:
    """Compute a lightweight signature from raw data to detect
    material market state changes that invalidate cached LLM points.

    Uses: spot price, vix, st_consensus from 5m, rsi from 5m.
    """
    try:
        spot = raw_data.get("macro", {}).get("indicators", {}).get("spot", 0)
        vix = raw_data.get("macro", {}).get("indicators", {}).get("vix", 0)
        st = (
            raw_data.get("trend", {})
            .get("timeframes", {})
            .get("5m", {})
            .get("st_consensus", "")
        )
        rsi = (
            raw_data.get("momentum", {})
            .get("timeframes", {})
            .get("5m", {})
            .get("rsi", 0)
        )

        # Bucket to avoid re-caching on minor noise
        spot_bucket = int(float(spot or 0) / 50) * 50
        rsi_bucket = int(float(rsi or 50) / 10) * 10

        return f"spot:{spot_bucket}|vix:{vix}|st:{st}|rsi:{rsi_bucket}"
    except (TypeError, ValueError, KeyError):
        return ""
